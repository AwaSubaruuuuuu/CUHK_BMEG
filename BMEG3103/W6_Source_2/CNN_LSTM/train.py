# -*- coding: utf-8 -*-
"""
train.py — Flickr8k Image Captioning (CNN(DenseNet201) + LSTM)

Adapted from the GitHub project:
  CHAITANYAI0/Image-Captioning-with-CNN-LSTM-and-ResNet-GRU-Flickr8k's CNN_LSTM.ipynb

Pipeline:
  1. Load data/captions.csv (generated by download_data.py)
  2. Text preprocessing + Tokenizer
  3. Extract 1920-dim features for each image using pretrained DenseNet201 (cached to data/features_DenseNet.pkl)
  4. Build a CNN+LSTM model and train it (best weights saved to output/model.keras)
  5. Plot the loss curve, predict captions for validation samples, and compute BLEU-4

Usage:
  python train.py
  python train.py --epochs 15 --batch-size 64
"""
import argparse
import os
import pickle
import re

import matplotlib
matplotlib.use("Agg")  # Do not open a window; save directly to file
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from tqdm import tqdm

import tensorflow as tf
from tensorflow.keras.applications import DenseNet201
from tensorflow.keras.callbacks import EarlyStopping, ModelCheckpoint, ReduceLROnPlateau
from tensorflow.keras.layers import (Dense, Dropout, Embedding, Input, LSTM, Reshape,
                                     add, concatenate)
from tensorflow.keras.models import Model
from tensorflow.keras.preprocessing.image import img_to_array, load_img
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.utils import Sequence, to_categorical

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, "data")
OUTPUT_DIR = os.path.join(BASE_DIR, "output")
IMG_SIZE = 224


# ---------------------------------------------------------------------------
# 1. Load data and text preprocessing (corresponds to notebook cells 5~10)
# ---------------------------------------------------------------------------
def load_captions() -> pd.DataFrame:
    csv_path = os.path.join(DATA_DIR, "captions.csv")
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Cannot find {csv_path}. Please run first: python download_data.py")
    data = pd.read_csv(csv_path)
    return data


def text_preprocessing(data: pd.DataFrame) -> pd.DataFrame:
    """Lowercase, remove non-English characters and single-letter words, and add startseq / endseq"""
    def clean(x: str) -> str:
        x = str(x).lower()
        x = re.sub(r"[^a-z\s]", "", x)          # Keep only English letters
        x = re.sub(r"\s+", " ", x).strip()       # Collapse whitespace
        x = " ".join(w for w in x.split() if len(w) > 1)
        return x

    data["caption"] = data["caption"].apply(clean)
    data["caption"] = "startseq " + data["caption"] + " endseq"
    return data


# ---------------------------------------------------------------------------
# 2. Feature extraction (corresponds to notebook cells 12~14)
# ---------------------------------------------------------------------------
def extract_features(data: pd.DataFrame, image_path: str) -> dict:
    cache_path = os.path.join(DATA_DIR, "features_DenseNet.pkl")
    if os.path.exists(cache_path):
        print(f"[features] Using cache {cache_path}")
        with open(cache_path, "rb") as f:
            features = pickle.load(f)
    else:
        base = DenseNet201()
        fe = Model(inputs=base.input, outputs=base.layers[-2].output)
        features = {}
        for image in tqdm(data["image"].unique().tolist(), desc="Extracting DenseNet201 features"):
            p = os.path.join(image_path, image)
            if not os.path.exists(p):
                continue
            img = load_img(p, target_size=(IMG_SIZE, IMG_SIZE))
            img = img_to_array(img) / 255.0
            img = np.expand_dims(img, axis=0)
            features[image] = fe.predict(img, verbose=0)
        with open(cache_path, "wb") as f:
            pickle.dump(features, f)
        print(f"[features] Cached to {cache_path}")
    return features


# ---------------------------------------------------------------------------
# 3. Data generator (corresponds to notebook cell 15)
# ---------------------------------------------------------------------------
class CustomDataGenerator(Sequence):
    def __init__(self, df, X_col, y_col, batch_size, directory,
                 tokenizer, vocab_size, max_length, features, shuffle=True):
        self.df = df.copy()
        self.X_col = X_col
        self.y_col = y_col
        self.directory = directory
        self.batch_size = batch_size
        self.tokenizer = tokenizer
        self.vocab_size = vocab_size
        self.max_length = max_length
        self.features = features
        self.shuffle = shuffle
        self.n = len(self.df)

    def on_epoch_end(self):
        if self.shuffle:
            self.df = self.df.sample(frac=1).reset_index(drop=True)

    def __len__(self):
        return self.n // self.batch_size

    def __getitem__(self, index):
        batch = self.df.iloc[index * self.batch_size:(index + 1) * self.batch_size, :]
        X1, X2, y = self.__get_data(batch)
        return (X1, X2), y

    def __get_data(self, batch):
        X1, X2, y = [], [], []
        images = batch[self.X_col].tolist()
        for image in images:
            if image not in self.features:
                continue
            feature = self.features[image][0]
            captions = batch.loc[batch[self.X_col] == image, self.y_col].tolist()
            for caption in captions:
                seq = self.tokenizer.texts_to_sequences([str(caption)])[0]
                for i in range(1, len(seq)):
                    in_seq, out_seq = seq[:i], seq[i]
                    in_seq = pad_sequences([in_seq], maxlen=self.max_length)[0]
                    out_seq = to_categorical([out_seq], num_classes=self.vocab_size)[0]
                    X1.append(feature)
                    X2.append(in_seq)
                    y.append(out_seq)
        return np.array(X1), np.array(X2), np.array(y)


# ---------------------------------------------------------------------------
# 4. Model (corresponds to notebook cell 17)
# ---------------------------------------------------------------------------
def build_model(max_length: int, vocab_size: int) -> Model:
    input1 = Input(shape=(1920,))                      # DenseNet201 features (layer before pooling)
    input2 = Input(shape=(max_length,))                # Partial caption sequence

    img_features = Dense(256, activation="relu")(input1)
    img_features_reshaped = Reshape((1, 256))(img_features)

    sentence_features = Embedding(vocab_size, 256, mask_zero=False)(input2)
    merged = concatenate([img_features_reshaped, sentence_features], axis=1)
    sentence_features = LSTM(256)(merged)
    x = Dropout(0.5)(sentence_features)
    x = add([x, img_features])
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.5)(x)
    output = Dense(vocab_size, activation="softmax")(x)

    caption_model = Model(inputs=[input1, input2], outputs=output)
    caption_model.compile(loss="categorical_crossentropy", optimizer="adam")
    return caption_model


# ---------------------------------------------------------------------------
# 5. Predict captions (corresponds to notebook cells 26~27)
# ---------------------------------------------------------------------------
def idx_to_word(integer, tokenizer):
    for word, index in tokenizer.word_index.items():
        if index == integer:
            return word
    return None


def predict_caption(model, image, tokenizer, max_length, features):
    if image not in features:
        return ""
    feature = features[image]
    in_text = "startseq"
    for _ in range(max_length):
        sequence = tokenizer.texts_to_sequences([in_text])[0]
        sequence = pad_sequences([sequence], max_length)
        y_pred = model.predict([feature, sequence], verbose=0)
        y_pred = np.argmax(y_pred)
        word = idx_to_word(y_pred, tokenizer)
        if word is None:
            break
        in_text += " " + word
        if word == "endseq":
            break
    return in_text


def plot_loss(history, out_path):
    plt.figure(figsize=(20, 8))
    plt.plot(history.history["loss"])
    plt.plot(history.history["val_loss"])
    plt.title("model loss")
    plt.ylabel("loss")
    plt.xlabel("epoch")
    plt.legend(["train", "val"], loc="upper left")
    plt.savefig(out_path, dpi=120, bbox_inches="tight")
    plt.close()
    print(f"[plot] Loss curve saved to {out_path}")


# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--epochs", type=int, default=15, help="Number of training epochs (original notebook used 50; on CPU, 10~15 is recommended first)")
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--eval-samples", type=int, default=15, help="How many validation images to sample for BLEU after training")
    args = parser.parse_args()

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    image_path = os.path.join(DATA_DIR, "Images")

    # --- Data ---
    data = load_captions()
    data = text_preprocessing(data)
    captions = data["caption"].tolist()

    tokenizer = Tokenizer()
    tokenizer.fit_on_texts(captions)
    vocab_size = len(tokenizer.word_index) + 1
    max_length = max(len(c.split()) for c in captions)
    print(f"[data] Vocabulary size vocab_size = {vocab_size}, longest caption max_length = {max_length}")

    images = data["image"].unique().tolist()
    nimages = len(images)
    split_index = round(0.85 * nimages)
    train_images = images[:split_index]
    val_images = images[split_index:]

    train = data[data["image"].isin(train_images)].reset_index(drop=True)
    test = data[data["image"].isin(val_images)].reset_index(drop=True)
    print(f"[data] Training {len(train)} captions / Validation {len(test)} captions")

    # --- Features ---
    features = extract_features(data, image_path)

    # --- Save tokenizer for inference ---
    with open(os.path.join(OUTPUT_DIR, "tokenizer.pkl"), "wb") as f:
        pickle.dump({"tokenizer": tokenizer, "max_length": max_length,
                     "vocab_size": vocab_size}, f)

    # --- Generators ---
    train_generator = CustomDataGenerator(
        df=train, X_col="image", y_col="caption", batch_size=args.batch_size,
        directory=image_path, tokenizer=tokenizer, vocab_size=vocab_size,
        max_length=max_length, features=features)
    validation_generator = CustomDataGenerator(
        df=test, X_col="image", y_col="caption", batch_size=args.batch_size,
        directory=image_path, tokenizer=tokenizer, vocab_size=vocab_size,
        max_length=max_length, features=features)

    # --- Model and training ---
    caption_model = build_model(max_length, vocab_size)
    caption_model.summary()

    model_path = os.path.join(OUTPUT_DIR, "model.keras")
    checkpoint = ModelCheckpoint(model_path, monitor="val_loss", mode="min",
                                 save_best_only=True, verbose=1)
    earlystopping = EarlyStopping(monitor="val_loss", min_delta=0, patience=5,
                                  verbose=1, restore_best_weights=True)
    learning_rate_reduction = ReduceLROnPlateau(monitor="val_loss", patience=3,
                                                verbose=1, factor=0.2, min_lr=1e-8)

    history = caption_model.fit(
        train_generator,
        epochs=args.epochs,
        validation_data=validation_generator,
        callbacks=[checkpoint, earlystopping, learning_rate_reduction])

    plot_loss(history, os.path.join(OUTPUT_DIR, "loss.png"))

    # --- BLEU evaluation (corresponds to notebook cell 32) ---
    try:
        import nltk
        from nltk.translate.bleu_score import sentence_bleu
        try:
            nltk.data.find("tokenizers/punkt")
        except LookupError:
            nltk.download("punkt", quiet=True)

        samples = test.drop_duplicates("image").sample(min(args.eval_samples, 15),
                                                       random_state=42).reset_index(drop=True)
        scores = []
        for _, record in samples.iterrows():
            pred = predict_caption(caption_model, record["image"], tokenizer,
                                   max_length, features)
            pred_clean = pred.replace("startseq", "").replace("endseq", "").strip()
            ref_tokens = nltk.word_tokenize(str(record["caption"]).lower())
            can_tokens = nltk.word_tokenize(pred_clean.lower())
            if not can_tokens:
                continue
            score = sentence_bleu([ref_tokens], can_tokens,
                                  weights=(0.25, 0.25, 0.25, 0.25))
            scores.append(score)
            print(f"  Image: {record['image']}\n  Prediction: {pred_clean}\n  Reference: {record['caption']}\n  BLEU-4: {score:.4f}\n")
        if scores:
            print(f"Average BLEU-4 score: {np.mean(scores):.4f}")
    except Exception as e:  # Skip if nltk is unavailable
        print(f"[skip] BLEU evaluation failed: {e}")

    print(f"\nTraining complete! Best model: {model_path}")
    print("To run inference on any image: python predict.py your_image.jpg")


if __name__ == "__main__":
    main()